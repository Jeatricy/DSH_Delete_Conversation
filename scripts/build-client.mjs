import { readFile, mkdir, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const source = await readFile(new URL('src/client.js', root), 'utf8');
const dictionaries = Object.fromEntries(await Promise.all(['en', 'zh'].map(async (lang) => [
  lang, JSON.parse(await readFile(new URL(`locale/${lang}.json`, root), 'utf8')),
])));
const artifact = `// Generated by scripts/build-client.mjs; edit src/client.js and locale/*.json.\nwindow.__ModuleLoader__.load({\n  id: 'dsh-delete-conversation',\n  factory(require) {\n${source.replace('export function createClientPlugin', 'function createClientPlugin')}\n    return createClientPlugin(require('react'), ${JSON.stringify(dictionaries)});\n  },\n});\n`;
await mkdir(new URL('dist/', root), { recursive: true });
await writeFile(new URL('dist/client.js', root), artifact);
console.log('Built dist/client.js');
